import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Receipts } from './receipt_engine.mjs';
const json=p=>JSON.parse(readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const r=new Receipts(fileURLToPath(new URL('../state/collection.db',import.meta.url)),json(new URL('../config.json',import.meta.url)),json(new URL('../local/payment_account.json',import.meta.url)));
const [cmd,arg,...rest]=process.argv.slice(2);
try{let result;
 if(cmd==='capture')result=r.capture(json(arg));
 else if(cmd==='approve')result=r.approve(arg,json(rest[0]));
 else if(cmd==='assess')result=r.assess(arg,json(rest[0]));
 else if(cmd==='request-review')result=r.requestReview(arg);
 else if(cmd==='review-sent')result=r.reviewSent(arg,rest.join(' '));
 else if(cmd==='friend-confirm')result=r.friendConfirm(arg,json(rest[0]));
 else if(cmd==='recheck')result=r.recheck(arg,rest.join(' '));
 else if(cmd==='reserve')result=r.reserve(arg,json(rest[0]));
 else if(cmd==='verify')result=r.verify(arg,json(rest[0]));
 else if(cmd==='reject')result=r.reject(arg,rest.join(' '));
 else if(cmd==='unknown')result=r.unknown(arg,rest.join(' '));
 else if(cmd==='ack')result=r.acknowledge(arg,json(rest[0]));
 else if(cmd==='confirm-ack')result=r.confirmAck(arg,rest.join(' '));
 else if(cmd==='show')result=r.get(arg);
 else if(cmd==='status')result=r.list();
 else throw Error('Use capture/approve/reserve/verify/reject/unknown/ack/confirm-ack/show/status');
 console.log(JSON.stringify(result,null,2));
}catch(e){console.error(e.message);process.exitCode=1;}finally{r.close();}
