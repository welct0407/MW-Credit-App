-- New inbox work is committed together with ingress and audit before HTTP 200.
-- Never consume a PostgreSQL sequence using a sole MAX(id) watermark: concurrent
-- transactions can commit out of allocation order. Claim durable work rows instead.
CREATE TABLE runtime.ingress_work (
 message_id text PRIMARY KEY REFERENCES runtime.ingress_messages(message_id),
 state text NOT NULL CHECK(state IN ('PENDING','RESERVED','DONE','IGNORED','REVIEW')),
 eligible_at timestamptz NOT NULL,
 claimed_by uuid,
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX ingress_work_due_idx ON runtime.ingress_work(eligible_at,message_id) WHERE state='PENDING';
CREATE INDEX ingress_messages_sender_time_idx ON runtime.ingress_messages(sender_id,event_timestamp DESC);
CREATE INDEX receipt_jobs_due_idx ON runtime.receipt_jobs(status,retry_after,created_at);
CREATE INDEX receipt_emails_due_idx ON runtime.receipt_emails(status,retry_after);
CREATE INDEX notices_due_idx ON runtime.partner_notices(stream,email_status,retry_after);
CREATE INDEX notices_message_idx ON runtime.partner_notices(stream,message_id) WHERE message_id IS NOT NULL;
CREATE INDEX turns_binding_time_idx ON runtime.conversation_turns(binding,created_at);
CREATE INDEX api_unknown_idx ON runtime.conversation_operations(state) WHERE state='UNKNOWN';
CREATE INDEX dml_unknown_idx ON runtime.conversation_dml(state) WHERE state='UNKNOWN';
CREATE INDEX api_fingerprint_idx ON runtime.conversation_operations(fingerprint);
CREATE INDEX statement_email_due_idx ON runtime.cash_statement_emails(retry_after) WHERE status='EMAIL_REJECTED';

-- Immutable statement snapshots currently live in JSON files; preserve those files
-- at cutover. A copy here allows later rebuilds without requerying changed balances.
CREATE TABLE runtime.statement_snapshots (
 snapshot_key text PRIMARY KEY,
 period_start timestamptz NOT NULL,
 period_end timestamptz NOT NULL CHECK(period_end>period_start),
 basis text NOT NULL,
 payload_text text NOT NULL,
 payload_sha256 text NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 source_file text,
 frozen_at timestamptz NOT NULL
);
CREATE TRIGGER statement_snapshot_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON runtime.statement_snapshots
 FOR EACH STATEMENT EXECUTE FUNCTION audit.reject_rewrite();

