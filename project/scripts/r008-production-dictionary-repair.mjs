import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
const file='Documents/AppSheet_Data_Dictionary.xlsx',out='outputs/r008-20260918/production';
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(file));
const sh=wb.worksheets.getItem('App Settings');
const rows=sh.getUsedRange().values;
const i=rows.findIndex(r=>r[0]==='OLAP PROD'&&r[1]==='Settlements'&&r[2]==='Security filter');
assert(i>=0); sh.getRangeByIndexes(i,3,1,1).setNumberFormat('@'); sh.getRangeByIndexes(i,3,1,1).values=[["'=[Status] <> \"Cancelled\""]];
wb.recalculate();
const scan=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:50}});
const matches=scan.ndjson.trim().split(/\r?\n/).filter(Boolean).map(line=>JSON.parse(line)).filter(x=>x.kind==='match');
if(matches.length)throw Error(`Workbook error: ${scan.ndjson}`);
const output=`${out}/AppSheet_Data_Dictionary.xlsx`; await(await SpreadsheetFile.exportXlsx(wb)).save(output);
const check=await SpreadsheetFile.importXlsx(await FileBlob.load(output));
const cell=check.worksheets.getItem('App Settings').getRangeByIndexes(i,3,1,1);
assert.equal(String(cell.values[0][0]).replace(/^'/,''),'=[Status] <> "Cancelled"'); assert.equal(cell.formulas[0][0]??'','');
await fs.copyFile(output,file); await fs.writeFile(`${out}/dictionary-error-scan.jsonl`,'');
const verification=JSON.parse(await fs.readFile(`${out}/dictionary-verification.json`,'utf8')); verification.errorScanLines=0; verification.literalExpressionRepair='App Settings!D84 retained as text';
await fs.writeFile(`${out}/dictionary-verification.json`,JSON.stringify(verification,null,2)+'\n');
console.log(JSON.stringify({repaired:true,cell:`D${i+1}`,value:cell.values[0][0],formula:cell.formulas[0][0]??'',errors:0}));
