import fs from 'node:fs/promises';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';

const file='Documents/AppSheet_Data_Dictionary.xlsx';
const out='outputs/r007-20260918';
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(file));
const sh=wb.worksheets.getItem('Dev Differences');
const used=sh.getUsedRange();
const beforeValues=used.values;
const beforeFormulas=used.formulas;
const record=['R007 production closure\n2026-09-18','Release closure','PROD target / evidence','PROD OLAP 1.100131 and SQL V22 match the promoted R007 delta; PROD OLTP 3.000173 unchanged. Saved editor readback, diagnostics, runtime smoke and production SQL evidence are in outputs/r007-20260918.','Released after owner approval; DEV difference closed. Prototype schedule warnings remain explicitly excluded for DEV only.'];
const row=beforeValues.length;
const dest=sh.getRangeByIndexes(row,0,1,5);
dest.setNumberFormat('@');
dest.values=[record];
dest.format.wrapText=true;
dest.format.rowHeight=120;
wb.recalculate();
const verification={sheet:'Dev Differences',addedRows:1,range:`A${row+1}:E${row+1}`,release:'R007',productionClosed:true,prodOlapVersion:'1.100131',prodOltpVersion:'3.000173',sqlVersion:'V22'};
const preview=await wb.render({sheetName:sh.name,range:`A${row+1}:E${row+1}`,scale:1,format:'png'});
await fs.writeFile(`${out}/dictionary-promotion.png`,new Uint8Array(await preview.arrayBuffer()));
const output=`${out}/AppSheet_Data_Dictionary.xlsx`;
await(await SpreadsheetFile.exportXlsx(wb)).save(output);
const reopened=await SpreadsheetFile.importXlsx(await FileBlob.load(output));
const after=reopened.worksheets.getItem('Dev Differences').getUsedRange();
if(after.values.length!==beforeValues.length+1)throw Error('Unexpected Dev Differences row count');
if(JSON.stringify(after.values.slice(0,beforeValues.length))!==JSON.stringify(beforeValues))throw Error('Existing dictionary values changed');
if(JSON.stringify(after.formulas.slice(0,beforeFormulas.length))!==JSON.stringify(beforeFormulas))throw Error('Existing dictionary formulas changed');
await fs.writeFile(`${out}/dictionary-promotion-verification.json`,JSON.stringify(verification,null,2)+'\n');
console.log(JSON.stringify(verification));
