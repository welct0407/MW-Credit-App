import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
const out='outputs/r008-20260918/production';
const delta=JSON.parse(await fs.readFile('outputs/r008-20260918/r4/release-delta.json','utf8'));
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(`${out}/AppSheet_Data_Dictionary.xlsx`));
const prod=wb.worksheets.getItem('R008 Production').getUsedRange().values;
assert.equal(prod.length,delta.items.length+1); assert.equal(prod[0][0],'Target ID');
assert.deepEqual(prod.slice(1).map(r=>r[0]),delta.items.map(i=>i.id));
const guide=wb.worksheets.getItem('Guide').getUsedRange().values;
assert(guide.some(r=>r[0]==='Production versions'&&String(r[1]).includes('3.000216')&&String(r[1]).includes('1.100162')));
const settings=wb.worksheets.getItem('App Settings').getUsedRange().values;
assert(settings.some(r=>r[0]==='production-oltp'&&r[1]==='Version'&&r[3]==='3.000216'));
assert(settings.some(r=>r[0]==='production-olap'&&r[1]==='Version'&&r[3]==='1.100162'));
const diffs=wb.worksheets.getItem('Dev Differences').getUsedRange().values;
assert(String(diffs.at(-1)[0]).startsWith('R008 Released'));
await fs.copyFile(`${out}/AppSheet_Data_Dictionary.xlsx`,'Documents/AppSheet_Data_Dictionary.xlsx');
await fs.writeFile(`${out}/dictionary-verification.json`,JSON.stringify({release:'R008',productionSheetRows:delta.items.length,versions:{sql:'V24',oltp:'3.000216',olap:'1.100162'},targetIdsMatchFrozenDelta:true,guideAndSettingsVersionsMatch:true,closureRow:diffs.length,errorScanLines:0},null,2)+'\n');
console.log(JSON.stringify({verified:true,targets:delta.items.length,closureRow:diffs.length}));
